export function getDistrictFromPostal(postalCode) {
  if (!postalCode || postalCode.length < 2) return null;
  const prefix = postalCode.substring(0, 2);
  return POSTAL_DISTRICT_MAP[prefix] || null;
}

export function getProximityScore(consultantZone, projectZone) {
  if (!consultantZone || !projectZone) return 0.5; // neutral if unknown
  const row = ZONE_PROXIMITY[consultantZone];
  if (!row) return 0.5;
  return row[projectZone] ?? 0.5;
}

export function getProximityLabel(score) {
  if (score >= 0.9) return { label: "Same area", color: "#16a34a", icon: "📍" };
  if (score >= 0.7) return { label: "Nearby", color: "#16a34a", icon: "📍" };
  if (score >= 0.5) return { label: "Manageable", color: "#d97706", icon: "🚇" };
  if (score >= 0.3) return { label: "~30–45 min", color: "#d97706", icon: "🚇" };
  return { label: "Far end of island", color: "#dc2626", icon: "🚌" };
}
